"""Generates the Node reference of the docs (docs/reference/nodes) from the code.

    python generate_node_reference.py <dump.json | tool_node_reference_dump executable> [--check]

The input is what tool_node_reference_dump writes (a CMake target of the
Engine; give the executable and this script runs it): the node contract
inventory, the same document test_node_contract_gates checks, with each node's
palette placement and Node Documentation text added. From it this script
writes:

- docs/reference/nodes/index.md: every node by category, with its status;
- docs/reference/nodes/categories/<category>.md: one page per category;
- docs/reference/nodes/<category>/<node>.md: one page per node, with what it
  does, its input and output pins, every setting (type, default, allowed
  values, whether a run reads it or only the editor), where it runs, its
  support, usage, tips and the committed example graphs that use it.

Nodes that cannot run yet (templates, blocked nodes, previews) and deprecated
nodes are listed as such. Only nodes of dropped features (DROPPED_FEATURE) are
left out, as the docs rules require.

Hand notes: docs/reference/nodes/_notes/<category>.md is added to the end of
the category page, docs/reference/nodes/_notes/<category>/<node>.md to the end
of the node page. A note may start with front matter whose related,
redirect_from, description, area and owner replace the generated ones. A
note's relative links (and its related and redirect_from paths) are written as
seen from the page it joins: categories/ for a category note, <category>/ for
a node note; check_docs.py checks them there.

Each page starts with the docs front matter (generated: true). last_reviewed,
since and status are kept from the committed page, so regenerating does not
change them; set them by hand after someone has read the page. Internal ticket
numbers are left out of the text.

With --check nothing is written: the script exits 1 and names each page whose
committed text differs from what the code gives (and each generated page the
code no longer gives), so a node change cannot land without its page.
"""
import datetime
import os
import re
import subprocess
import sys
import tempfile
import json

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from generate_extension_reference import drop_tickets  # noqa: E402  (one ticket filter for every generator)

REPO = os.path.dirname(os.path.dirname(HERE))
DOCS = os.path.join(REPO, "docs")
NODES = os.path.join(DOCS, "reference", "nodes")
NOTES = os.path.join(NODES, "_notes")
GENERATOR = "scripts/docs/generate_node_reference.py"
NOTICE = ("<!-- Generated by {0} from the node registry; do not edit. Change the node's metadata or "
          "the notes in docs/reference/nodes/_notes (ctest node_reference_docs fails until the pages "
          "match). -->\n").format(GENERATOR)
DEFAULT_META = {"area": "graph-editor", "owner": "graph-editor", "audience": "user",
                "status": "experimental", "since": "1.0.8"}

# The words the Properties panel shows for each setting type (node_metadata.h).
TYPE_WORDS = {
    "int": "Integer", "float": "Number", "bool": "On / off", "enum": "Choice", "string": "Text",
    "multiline": "Text (several lines)", "password": "Password", "file": "File", "directory": "Folder",
    "channels": "One number per channel", "fixed": "Fixed (set by the Engine)",
    "column": "Column of the incoming data", "dropdown": "Choice",
}
PIN_WORDS = {"tensor": "Tensor", "labels": "Labels", "parameters": "Parameters", "loss": "Loss",
             "optimizer": "Optimizer", "dataset": "Dataset", "environment": "Environment"}
# Nodes of dropped features are never published (docs rule: nothing about
# dropped features); they stay in the dump and in the findings until the code
# removes them.
DROPPED_FEATURE = re.compile(r"hugging\s*face", re.I)
TRAINING_ROLES = {
    "model_layer": "a layer of the model", "activation": "an activation of the model", "loss": "the loss",
    "optimizer": "the optimizer", "data_source": "the data source", "preprocessing": "a preprocessing step",
    "training_control": "a training control", "training_workflow": "a training workflow step",
}


# ------------------------------------------------------------------ input --

def load_dump(source):
    """The dump: read a JSON file, or run the dump tool and read what it writes."""
    if source.lower().endswith(".json"):
        with open(source, encoding="utf-8") as f:
            return json.load(f)
    with tempfile.TemporaryDirectory() as folder:
        out = os.path.join(folder, "node_reference.json")
        subprocess.run([source, "--out", out], check=True, stdout=subprocess.DEVNULL)
        with open(out, encoding="utf-8") as f:
            return json.load(f)


# ------------------------------------------------------------------- text --

def slug(text):
    text = text.replace("I/O", "IO")
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "node"


def sentence(text):
    """Text that ends like a sentence."""
    text = text.strip()
    return text + "." if text and text[-1] not in ".!?:)" else text


def clean(text):
    """Code text made safe for Markdown prose: no ticket numbers, no stray HTML or emphasis."""
    text = drop_tickets(text or "").strip()
    text = text.replace("<", "&lt;").replace("*", "\\*")
    return re.sub(r"[ \t]+\n", "\n", text)


def cell(text):
    """Text for one table cell."""
    return re.sub(r"\s*\n\s*", " ", clean(text)).replace("|", "\\|") or " "


def code(value):
    value = str(value)
    if value == "":
        return "(empty)"
    tick = "``" if "`" in value else "`"
    pad = " " if "`" in value else ""
    return "{0}{1}{2}{1}{0}".format(tick, pad, value.replace("|", "\\|"))


def first_sentence(text, limit=158):
    text = re.sub(r"\s+", " ", drop_tickets(text or "")).strip()
    m = re.match(r"(.+?(?<!e\.g)(?<!i\.e)[.!?])(\s+(?=[A-Z])|$)", text)
    first = m.group(1) if m else text
    if len(first) > limit:
        first = first[:limit - 3].rsplit(" ", 1)[0].rstrip(",;:") + "..."
    return sentence(first)


def yaml_value(value):
    if re.search(r":\s|\s#|^[\[\]{}&*!|>'\"%@`-]|^\s|\s$", value) or value == "":
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return value


# ---------------------------------------------------------- front matter --

def read_front_matter(path):
    """(fields, body) of a Markdown file with simple front matter (scalars and '- item' lists)."""
    if not os.path.exists(path):
        return {}, ""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"---\n(.*?)\n---\n?", text, flags=re.S)
    if not m:
        return {}, text
    fields, key = {}, None
    for line in m.group(1).splitlines():
        item = re.match(r"^\s+-\s+(.*)$", line)
        if item and key:
            fields.setdefault(key, [])
            if isinstance(fields[key], list):
                fields[key].append(item.group(1).strip())
            continue
        kv = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if kv:
            key, raw = kv.group(1), kv.group(2).strip()
            if raw == "[]" or raw == "":
                fields[key] = []
            else:
                if len(raw) > 1 and raw[0] == raw[-1] == '"':
                    raw = raw[1:-1].replace('\\"', '"').replace("\\\\", "\\")
                fields[key] = raw
    return fields, text[m.end():]


def front_matter(path, meta):
    """The front matter of a generated page; review fields come from the committed page."""
    committed, _ = read_front_matter(path)
    today = datetime.date.today().isoformat()
    lines = ["---",
             "title: " + yaml_value(meta["title"]),
             "description: " + yaml_value(meta["description"]),
             "type: reference",
             "area: " + meta.get("area", DEFAULT_META["area"]),
             "audience: " + DEFAULT_META["audience"],
             "status: " + (committed.get("status") or DEFAULT_META["status"]),
             "since: " + (committed.get("since") or DEFAULT_META["since"]),
             "owner: " + meta.get("owner", DEFAULT_META["owner"]),
             "last_reviewed: " + (committed.get("last_reviewed") or today),
             "generated: true"]
    for name in ("related", "redirect_from"):
        values = meta.get(name) or []
        if values:
            lines.append(name + ":")
            lines.extend("  - " + v for v in values)
    lines.append("---")
    return "\n".join(lines) + "\n\n" + NOTICE + "\n"


def note(*parts):
    """(fields, body) of a hand note, or ({}, "") when there is none."""
    path = os.path.join(NOTES, *parts)
    if not os.path.exists(path):
        return {}, ""
    fields, body = read_front_matter(path)
    return fields, body.strip("\n")


def with_note(meta, fields):
    meta = dict(meta)
    for name in ("related", "redirect_from"):
        if fields.get(name):
            meta[name] = (meta.get(name) or []) + [r for r in fields[name] if r not in (meta.get(name) or [])]
    for name in ("description", "area", "owner", "title"):
        if fields.get(name):
            meta[name] = fields[name]
    return meta


# ------------------------------------------------------------------ nodes --

def status_of(node):
    """(badge, sentence) for a node: whether it runs, and why not."""
    ref = node["reference"]
    place, why = ref["palette"]["place"], ref["palette"]["why"]
    badge = node.get("badge") or ""
    if ref.get("made_by"):
        return "Made from other nodes", "Not in the palette: " + clean(ref["made_by"])
    if place == "hidden":
        return "Deprecated", "Deprecated: not offered in the palette; saved graphs that use it still load."
    if place == "cant_run":
        return "Can't run yet", "Can't run yet ({}): the node is listed under **Can't run yet** in the palette " \
                                "and cannot be added to a graph.".format(clean(why))
    if node["metadata_status"] == "external":
        return "Runs (external)", "Runs when its external provider is installed."
    if badge and badge not in ("Coming Soon",):
        return "Runs ({})".format(clean(badge)), "Runs. Marked **{}** in the palette.".format(clean(badge))
    if place == "advanced":
        return "Runs", "Runs. In the palette under **Advanced operations > {}**.".format(clean(ref["palette"]["group"]))
    return "Runs", "Runs."


def pin_rows(pins):
    rows = ["| Pin | Type | Required | Connections | Meaning |", "| --- | --- | --- | --- | --- |"]
    for pin in pins:
        if pin["variadic"] or pin["max_connections"] != 1:
            most = "any number" if pin["max_connections"] <= 0 else str(pin["max_connections"])
            conn = "{} to {}".format(pin["min_connections"], most)
        else:
            conn = "1"
        rows.append("| **{}** | {} | {} | {} | {} |".format(
            cell(pin["name"]), PIN_WORDS.get(pin["type"], pin["type"]), "Yes" if pin["required"] else "No",
            conn, cell(pin["description"])))
    return rows


def allowed_values(param, labels):
    parts = []
    if param["choices"]:
        shown = []
        for i, value in enumerate(param["choices"]):
            label = labels[i] if i < len(labels) else ""
            shown.append(code(value) + (" ({})".format(cell(label)) if label and label != value else ""))
        parts.append(", ".join(shown))
    if param["validation"]:
        parts.append(code(param["validation"]))
    return "; ".join(parts) or " "


def setting_rows(node, legacy_params):
    ref = node["reference"]
    params = node["properties"]["declared"]
    groups = any(p["group"] for p in params)
    head = "| Setting | Key | Type | Default | Allowed values | Read by | Meaning |"
    if groups:
        head = "| Group " + head
    rows = [head, "|" + " --- |" * (head.count("|") - 1)]
    for p in params:
        meaning = p["description"] or legacy_params.get(p["name"], "")
        flags = []
        if p["required"]:
            flags.append("Required.")
        if p["advanced"]:
            flags.append("Advanced.")
        meaning = " ".join([sentence(cell(meaning))] + flags).strip() or " "
        row = "| {} | {} | {} | {} | {} | {} | {} |".format(
            cell(p["display_name"] or p["name"]), code(p["name"]), TYPE_WORDS.get(p["type"], cell(p["type"])),
            code(p["default"]), allowed_values(p, ref["choice_labels"].get(p["name"], [])),
            "The run" if p["consumption"] == "runtime" else "The editor only", meaning)
        rows.append(("| " + cell(p["group"]) + " " + row) if groups else row)
    return rows


def where_it_runs(node):
    ex = node["execution"]
    lines = []
    pipe = ex["pipeline"]
    if pipe["mode"] in ("operator_backed", "legacy_executor"):
        what = "Yes"
        if pipe["source_node"]:
            what += ", as a data source"
        if pipe["materializer"] not in ("none", "unknown"):
            what += "; the result can be saved as {}".format(
                {"arrow_table_only": "a table", "streaming_operators_only": "a stream"}.get(
                    pipe["materializer"], pipe["materializer"].replace("_", " ")))
        lines.append("| Data pipeline (run the graph, **Run step**, previews) | {} |".format(what))
    elif pipe["mode"] == "fail_closed":
        reason = cell(pipe["failure_reason"]) if pipe["failure_reason"] else "the pipeline refuses this node"
        lines.append("| Data pipeline (run the graph, **Run step**, previews) | No: {} |".format(reason))
    tr = ex["training"]
    if tr["declared"]:
        role = TRAINING_ROLES.get(tr["role"], "")
        if tr["training_supported"]:
            what = "Yes" + (", as " + role if role else "")
        elif tr["compile_supported"]:
            what = "Compiles, but does not train" + (" (" + role + ")" if role else "")
        else:
            what = "No"
        if tr["reason"]:
            what += ": " + cell(tr["reason"])
        lines.append("| Training (the compiled model) | {} |".format(what))
    if not lines:
        return []
    return ["| Where | Runs |", "| --- | --- |"] + lines


def support_rows(node):
    axes = node["execution"]["support_axes"]
    if not axes:
        return []
    rows = ["| Aspect | Value | Supported | Why |", "| --- | --- | --- | --- |"]
    previous = None
    for axis in axes:
        why = cell(axis["reason"]) if axis["reason"] != previous else "As above"
        previous = axis["reason"]
        rows.append("| {} | {} | {} | {} |".format(
            cell(axis["name"]), cell(axis["value"].replace("_", " ")), "Yes" if axis["supported"] else "No",
            why if axis["reason"] else " "))
    return rows


def node_page(node, cat, path, workflows):
    ref = node["reference"]
    legacy = ref.get("node_documentation") or {}
    legacy_params = {p["name"]: p["description"] for p in legacy.get("parameters", [])}
    doc = node["documentation"]
    brief = doc["brief"] or legacy.get("description", "")
    meta = {"title": node["name"] + " node",
            "description": first_sentence(brief) or "The {} node: its pins and settings.".format(node["name"]),
            "related": ["../categories/{}.md".format(cat["slug"])]}
    fields, extra = note(cat["slug"], node["slug"] + ".md")
    meta = with_note(meta, fields)
    badge, status_line = status_of(node)
    out = []
    if brief:
        out += [sentence(clean(brief)), ""]
    if status_line != "Runs.":
        out += ["**Status:** " + status_line, ""]
    if doc["help"] and doc["help"].strip() != (doc["brief"] or "").strip():
        out += [sentence(clean(doc["help"])), ""]
    out += ["| | |", "| --- | --- |",
            "| Category | [{}](../categories/{}.md) |".format(cell(cat["name"]), cat["slug"]),
            "| Status | {} |".format(badge)]
    names = [n for n in node["serialization"]["graph_import_names"] if n != node["name"]]
    if names:
        out.append("| Also read from graphs as | {} |".format(", ".join(code(n) for n in names)))
    if ref["keywords"]:
        out.append("| Search words | {} |".format(cell(", ".join(ref["keywords"]))))
    if ref["properties_editor"] == "dialog":
        out.append("| Settings | In its own window (double-click the node) |")
    out.append("")

    pins = node["pins"]
    out += ["## Inputs", ""]
    out += (pin_rows(pins["inputs"]) if pins["inputs"] else ["None: the node starts a branch of the graph."])
    out += ["", "## Outputs", ""]
    out += (pin_rows(pins["outputs"]) if pins["outputs"] else ["None: the node ends a branch of the graph."])
    if node["pins"]["factory_contract"] == "dynamic_provider_schema":
        out += ["", "The pins and settings of an extension node come from the plugin or Python node that "
                    "provides it; the extension's own page lists them."]
    out += ["", "## Settings", ""]
    if node["properties"]["declared"]:
        out += setting_rows(node, legacy_params)
        out += ["", "**Read by** says whether a run uses the setting (**The run**) or only the editor, "
                    "a dialog or a view (**The editor only**)."]
    else:
        out += ["The node has no settings."]
    runs = where_it_runs(node)
    if runs:
        out += ["", "## Where it runs", ""] + runs
    out += ["", "The node runs on the device chosen for the run (CPU or a GPU); a node does not fix a device."]
    support = support_rows(node)
    if support:
        out += ["", "## Support", ""] + support
    usage = [u for u in (node["evidence"]["documentation_usage_hint"], legacy.get("usage")) if u]
    if usage:
        out += ["", "## Usage", ""]
        for u in dict.fromkeys(usage):
            out += ["```text", drop_tickets(u).strip(), "```", ""]
        out.pop()
    if legacy.get("tips"):
        out += ["", "## Tips", ""] + ["- " + sentence(clean(t)) for t in legacy["tips"]]
    examples = [workflows[i] for i in node["evidence"]["representative_workflow_ids"] if i in workflows]
    if examples:
        out += ["", "## Examples", "", "Committed graphs in the Engine repository that use this node:", ""]
        for w in examples:
            line = "- `{}`".format(w["path"])
            if w["title"]:
                line += ": " + clean(w["title"])
            out.append(line)
    if extra:
        out += ["", extra]
    return front_matter(path, meta) + "\n".join(out).rstrip("\n") + "\n"


# ------------------------------------------------------- category / index --

def category_page(cat, path):
    nodes = cat["nodes"]
    running = sum(1 for n in nodes if status_of(n)[0].startswith("Runs"))
    meta = {"title": "{} nodes".format(cat["name"]),
            "description": "The {} nodes of the {} group: what each does and whether it runs.".format(
                len(nodes), cat["name"])}
    fields, extra = note(cat["slug"] + ".md")
    meta = with_note(meta, fields)
    rest = len(nodes) - running
    count = "{} node{}".format(len(nodes), "" if len(nodes) == 1 else "s")
    if rest == 0:
        tail = "it runs" if len(nodes) == 1 else "all run"
    else:
        tail = "{} run{}, {} cannot run yet or {} deprecated".format(
            running, "s" if running == 1 else "", rest, "is" if rest == 1 else "are")
    out = ["The **{}** group of the node palette has {}: {}.".format(cat["name"], count, tail),
           "", "| Node | Status | What it does |", "| --- | --- | --- |"]
    for n in nodes:
        out.append("| [{}](../{}/{}.md) | {} | {} |".format(
            cell(n["name"]), cat["slug"], n["slug"], status_of(n)[0],
            cell(first_sentence(n["documentation"]["brief"] or "", 200))))
    out += ["", "[All nodes](../index.md)"]
    if extra:
        out += ["", extra]
    return front_matter(path, meta) + "\n".join(out) + "\n"


def index_page(categories, path):
    total = sum(len(c["nodes"]) for c in categories)
    counts = {}
    for c in categories:
        for n in c["nodes"]:
            word = status_of(n)[0].split(" (")[0]
            counts[word] = counts.get(word, 0) + 1
    meta = {"title": "Node reference",
            "description": "Every node of the graph editor by category, with its status, pins and settings."}
    fields, extra = note("index.md")
    meta = with_note(meta, fields)
    summary = ", ".join("{} {}".format(v, k.lower() if k != "Runs" else "run") for k, v in sorted(
        counts.items(), key=lambda kv: (kv[0] != "Runs", kv[0])))
    out = ["The graph editor has {} nodes in {} categories ({}). Each node has a page with its inputs, "
           "outputs and every setting; a node that cannot run yet is listed, with why.".format(
               total, len(categories), summary),
           "", "| Status | Meaning |", "| --- | --- |",
           "| Runs | The node can be added to a graph and runs |",
           "| Can't run yet | Listed under **Can't run yet** in the palette, with why; it cannot be added to a graph |",
           "| Deprecated | No longer offered; saved graphs that use it still load |",
           "| Made from other nodes | Not in the palette; made another way (for example by grouping nodes) |",
           "", "## Categories", "", "| Category | Nodes |", "| --- | --- |"]
    for c in categories:
        out.append("| [{}](categories/{}.md) | {} |".format(cell(c["name"]), c["slug"], len(c["nodes"])))
    for c in categories:
        out += ["", "## " + c["name"], ""]
        out.append(" · ".join("[{}]({}/{}.md){}".format(
            cell(n["name"]), c["slug"], n["slug"],
            "" if status_of(n)[0].startswith("Runs") else " ({})".format(status_of(n)[0].lower()))
            for n in c["nodes"]))
    if extra:
        out += ["", extra]
    return front_matter(path, meta) + "\n".join(out) + "\n"


# -------------------------------------------------------------------- run --

def categories_of(dump):
    cats = {}
    for node in dump["nodes"]:
        if DROPPED_FEATURE.search(node["name"]):
            continue
        name = node["category"]
        cat = cats.setdefault(name, {"name": name, "slug": slug(name), "nodes": [],
                                     "order": node["reference"]["category_order"]})
        cat["nodes"].append(node)
    ordered = sorted(cats.values(), key=lambda c: (c["order"], c["name"]))
    for cat in ordered:
        cat["nodes"].sort(key=lambda n: (n["name"].lower(), n["identity"]["numeric"]))
        seen = {}
        for n in cat["nodes"]:
            s = slug(n["name"])
            n["slug"] = s if s not in seen else "{}-{}".format(s, n["identity"]["numeric"])
            seen[s] = True
    return ordered


def pages_of(dump):
    workflows = {w["id"]: w for w in dump.get("workflow_evidence_registry", [])}
    categories = categories_of(dump)
    pages = [("index.md", lambda p: index_page(categories, p))]
    for cat in categories:
        pages.append(("categories/{}.md".format(cat["slug"]), lambda p, c=cat: category_page(c, p)))
        for node in cat["nodes"]:
            pages.append(("{}/{}.md".format(cat["slug"], node["slug"]),
                          lambda p, n=node, c=cat: node_page(n, c, p, workflows)))
    return pages


def generated_pages():
    """Pages under docs/reference/nodes that say generated: true."""
    found = []
    for root, dirs, files in os.walk(NODES):
        dirs[:] = [d for d in dirs if d != "_notes"]
        for name in files:
            if name.endswith(".md"):
                path = os.path.join(root, name)
                with open(path, encoding="utf-8") as f:
                    if re.search(r"^generated:\s*true\s*$", f.read(3000), flags=re.M):
                        found.append(path)
    return found


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    check = "--check" in sys.argv
    if not args:
        print(__doc__)
        return 2
    dump = load_dump(os.path.abspath(args[0]))
    stale, written = [], set()
    for rel, render in pages_of(dump):
        path = os.path.join(NODES, *rel.split("/"))
        written.add(os.path.normcase(path))
        text = render(path)
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                current = f.read()
        if current == text:
            continue
        if check:
            stale.append("docs/reference/nodes/" + rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    for path in generated_pages():
        if os.path.normcase(path) in written:
            continue
        rel = os.path.relpath(path, REPO).replace(os.sep, "/")
        if check:
            stale.append(rel + " (no longer generated)")
        else:
            os.remove(path)
            print("removed " + rel)
            if not os.listdir(os.path.dirname(path)):
                os.rmdir(os.path.dirname(path))
    if stale:
        print("out of date (run python {} <tool_node_reference_dump>): {}{}".format(
            GENERATOR, ", ".join(stale[:20]), " and {} more".format(len(stale) - 20) if len(stale) > 20 else ""))
        return 1
    print("docs/reference/nodes: {} pages {}".format(len(written), "match the code" if check else "written"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
