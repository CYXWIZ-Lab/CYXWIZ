// Saved graphs store each node's NodeType as a number (graph_document.cpp reads the "type" integer), and
// saved RL policies compare layer kinds by number. Inserting or reordering a NodeType renumbers every type
// after it and breaks every graph and policy saved before (TOFIX212 F31: a merge shifted the RL types by 5).
//
// So NodeType is append-only: a new type goes immediately before Unknown, and gets one line at the end of the
// list below. This file fails to compile when a number moves; never edit an existing line to make it pass.
// A retired type keeps its name and number; core/graph_document.cpp refuses most retired types on load,
// naming what replaced them.

